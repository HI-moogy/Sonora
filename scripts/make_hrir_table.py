#!/usr/bin/env python3
"""Writes the head-related impulse responses (HRIRs) virtual surround uses.

Usage: make_hrir_table.py D1.zip

D1.zip is subject D1 (a Neumann KU100 dummy head) of the SADIE II database,
from https://www.york.ac.uk/sadie-project/database.html (Apache 2.0). Reads
its 48 kHz responses for the directions in DIRECTIONS, on the horizontal
plane, and writes crates/audio-engine/src/surround/hrir.rs. Needs only
Python's standard library.
"""

import math
import pathlib
import struct
import sys
import zipfile

# Degrees anticlockwise from straight ahead, as SADIE II measures them (90
# is the listener's left): the speakers of a 7.1 layout, plus straight
# behind so sound reflected off the back wall has somewhere to come from.
DIRECTIONS = (0, 30, 90, 150, 180, 210, 270, 330)
TAPS = 128
# Taps kept before the earliest sound reaches either ear, and taps faded
# out at the end, so trimming doesn't click.
LEAD = 8
FADE = 24
WAV_FOLDER = "D1/D1_HRIR_WAV/48K_24bit/"


def read_wav(data):
    """Each channel of a 24-bit PCM WAV, as floats."""
    assert data[:4] == b"RIFF" and data[8:12] == b"WAVE", "not a WAV file"
    pos, fmt, frames = 12, None, None
    while pos < len(data):
        chunk, size = data[pos : pos + 4], struct.unpack("<I", data[pos + 4 : pos + 8])[0]
        body = data[pos + 8 : pos + 8 + size]
        if chunk == b"fmt ":
            fmt = struct.unpack("<HHIIHH", body[:16])
        elif chunk == b"data":
            frames = body
        pos += 8 + size + (size & 1)
    tag, channels, rate, _, _, bits = fmt
    assert (tag, channels, rate, bits) == (1, 2, 48000, 24), f"unexpected format {fmt}"
    samples = [[], []]
    for frame in range(len(frames) // 6):
        for channel in range(2):
            at = frame * 6 + channel * 3
            samples[channel].append(int.from_bytes(frames[at : at + 3], "little", signed=True) / 8388608.0)
    return samples


def onset(response):
    """Where a response first reaches a tenth of its peak."""
    peak = max(abs(v) for v in response)
    return next(i for i, v in enumerate(response) if abs(v) > 0.1 * peak)


def energy(response):
    return sum(v * v for v in response)


def f32_literal(value):
    """The shortest decimal that reads back as the same f32."""
    exact = struct.unpack("<f", struct.pack("<f", value))[0]
    if exact == 0.0:
        return "0.0"
    for digits in range(1, 10):
        text = f"{exact:.{digits}e}"
        if struct.unpack("<f", struct.pack("<f", float(text)))[0] == exact:
            return text
    return repr(exact)


def main():
    archive = zipfile.ZipFile(sys.argv[1])
    raw = {azimuth: read_wav(archive.read(f"{WAV_FOLDER}azi_{azimuth},0_ele_0,0.wav")) for azimuth in DIRECTIONS}

    # One trim for every response, so the time differences between ears
    # (and directions) stay as measured.
    start = min(onset(ear) for pair in raw.values() for ear in pair) - LEAD
    fade = [0.5 * (1.0 + math.cos(math.pi * (i + 1) / (FADE + 1))) for i in range(FADE)]
    trimmed = {}
    for azimuth, pair in raw.items():
        ears = []
        for ear in pair:
            kept = ear[start : start + TAPS]
            for i in range(FADE):
                kept[TAPS - FADE + i] *= fade[i]
            ears.append(kept)
            print(f"{azimuth:3}°: kept {energy(kept) / energy(ear):.2%} of the energy", file=sys.stderr)
        trimmed[azimuth] = ears

    # One scale for every response, keeping their levels relative to each
    # other: a sound on a front speaker (30°) reaches both ears together
    # as loud as it would play on one side of the headphones.
    front = trimmed[30]
    scale = 1.0 / math.sqrt(energy(front[0]) + energy(front[1]))

    out = pathlib.Path(__file__).resolve().parent.parent / "crates/audio-engine/src/surround/hrir.rs"
    lines = [
        "//! Generated by `scripts/make_hrir_table.py` from the SADIE II database",
        "//! (subject D1, a Neumann KU100 dummy head, 48 kHz); don't edit by hand.",
        "//! Copyright 2018, University of York, under the Apache License 2.0: see",
        "//! `SADIE-II-NOTICE.txt` beside this file.",
        "",
        "/// Taps per ear in each [`Hrir`] (2.7 ms at 48 kHz).",
        f"pub(super) const TAPS: usize = {TAPS};",
        "",
        "/// How sound from one direction reaches each ear.",
        "pub(super) struct Hrir {",
        "    /// Degrees anticlockwise from straight ahead (90 is your left).",
        "    pub(super) azimuth: f32,",
        "    pub(super) left: [f32; TAPS],",
        "    pub(super) right: [f32; TAPS],",
        "}",
        "",
        "/// On the horizontal plane, in order of azimuth.",
        "#[rustfmt::skip]",
        f"pub(super) const HRIRS: [Hrir; {len(DIRECTIONS)}] = [",
    ]
    for azimuth in DIRECTIONS:
        lines.append(f"    Hrir {{ azimuth: {azimuth}.0,")
        for name, ear in zip(("left", "right"), trimmed[azimuth]):
            lines.append(f"        {name}: [")
            values = [f32_literal(v * scale) for v in ear]
            for row in range(0, TAPS, 8):
                lines.append("            " + ", ".join(values[row : row + 8]) + ",")
            lines.append("        ],")
        lines.append("    },")
    lines.append("];")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
